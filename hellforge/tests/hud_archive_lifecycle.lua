-- The same embedded chunk can be compiled more than once; only its owner may run.
local factory = assert(loadfile(arg[1]))
local first, second = factory(), factory()
first.on_enable()
first.on_update(0.25)
assert(updates == 1)
assert(not pcall(second.on_enable))
assert(second.on_disable() == true)
assert(first.on_disable() == false)
first.on_update(0.25)
assert(updates == 1)
allow_release = true
assert(first.on_cleanup_poll() == true)
second.on_enable()
assert(first.on_disable() == true)
second.on_update(0.25)
assert(updates == 2 and second.on_disable() == true)
