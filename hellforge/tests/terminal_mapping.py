"""Reproduce the 25480438 exact-byte guards. Pass the RVA-layout image (never the packed DLL).
Without --write the generated bytes must match the tracked Lua factory.
"""
import argparse
import hashlib
from pathlib import Path
import struct

DIGEST = '642b0aac0b4f577054993a965054827455ef143ced9895b2dfd09d1ecd433a37'
GUARDS = Path(__file__).resolve().parents[1] / 'hud/terminal_guards.lua'
# End-exclusive instruction ranges. Full callee includes the inlined target-build audio path.
RANGES = [
    ('definition_override_and_tail', 0x4fc110, 0x4fc1d1),
    ('resource_lookup', 0x4fbcf0, 0x4fbd82),
    ('gameplay_mode_4', 0x60c3a0, 0x60c3b0),
    ('instances', 0x984ec5, 0x984f4c),
    ('stages', 0x984f4c, 0x984f86),
    ('stage_bounds', 0x987783, 0x9877be),
    ('local_interactor', 0x9850df, 0x985147),
    ('network_owner_map', 0xfd9ba0, 0xfd9c68),
    ('override_allocation', 0x9930e0, 0x99312f),
    ('interactor_sentinels', 0x9840aa, 0x9840d2),
    ('in_use', 0x997a2f, 0x997a4a),
    ('local_argument', 0x985500, 0x985523),
    ('synced_stage_state', 0x9855c3, 0x9855e4),
    ('dispatch_and_call', 0x985809, 0x985862),
    ('dispatch_type_12', 0x98623c, 0x986240),
    ('action_index', 0x585b80, 0x585ba8),
    ('action_class_5', 0x585bbc, 0x585bc0),
    ('update_entry', 0x989750, 0x9897f2),
    ('timers_and_local_gate', 0x9897f2, 0x989860),
    ('directions_and_progress', 0x989860, 0x989916),
    ('host_progress_client_report', 0x989916, 0x9899b9),
    ('sync_and_audio', 0x9899b9, 0x989a98),
    ('arrow_sound', 0x989a98, 0x989b42),
    ('finish_timers', 0x989b42, 0x989bf7),
    ('stage_finish', 0x989bf7, 0x989c53),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('image', type=Path)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    data = args.image.read_bytes()
    assert hashlib.sha256(data).hexdigest() == DIGEST
    pe, = struct.unpack_from('<I', data, 60)
    assert struct.unpack_from('<I', data, pe + 8)[0] == 0x6ab3b43f

    def u32(at):
        return struct.unpack_from('<I', data, at)[0]

    def call(at):
        assert data[at] == 0xe8
        return at + 5 + struct.unpack_from('<i', data, at + 1)[0]

    assert u32(0x986210 + 11*4) == 0x985839 and call(0x98585d) == 0x989750
    assert call(0x9897ed) == 0x4fc110 and call(0x98512f) == 0xfd9ba0
    assert u32(0x4fc1b5) == u32(0x4fbd74) == 0x28b8
    assert all(call(at) == 0x585b80 for at in (0x98986a, 0x989898, 0x9898bf, 0x9898e6))
    assert u32(0x585ba8 + 5*4) == 0x585b9b and u32(0x98999e) == 0xe095a8ba
    lines = ['-- Generated from the mapped 25480438 image by tests/terminal_mapping.py.',
             'return {terminal_guards_25480438={']
    for name, start, end in RANGES:
        assert 0 < end - start <= 256
        literal = ''.join('\\%03d' % b for b in data[start:end])
        lines.append("    {name='%s',rva=0x%x,bytes='%s'}," % (name, start, literal))
    text = '\n'.join([*lines, '}}', ''])
    if args.write:
        GUARDS.write_text(text)
    assert GUARDS.read_text() == text
    print(f'PASS {len(RANGES)} target terminal witnesses, dispatch and call targets')


if __name__ == '__main__':
    main()
