#!/usr/bin/env python3
"""Generates Diver's Best Friend's address table for game build 25480438.

Usage (from hellforge/):
    python3 -I tools/map_addresses.py <R46 native-selection-poc> <game.dll> \\
        divers-best-friend/src/addresses_25480438.h receipts/addresses-25480438.json \\
        [--table tools/addresses_25480438.json] [--content-header hellforge_content.h] \\
        [--kind-names divers-best-friend/src/kind_names_25480438.h]
The defaults: the table beside this script, hellforge_content.h from $HF_SDK or else the vendored SDK (hellforge/sdk,
as build.sh uses), and kind_names_25480438.h beside the address header.

R46 (the last Lua DBF built for 25480438, its HellForge native-selection-poc folder) holds the build's addresses inline
in its Lua. tools/addresses_25480438.json names the ones the C port uses, each with the R46 line it comes from, and
assigns every R46 witness (guards.lua) the features it gates, or drops it. This script checks all of that and writes:

- the address header: DBF_FEATURE_*, DBF_RVA_* and DBF_OFF_* defines (addresses), DBF_VAL_* defines (the constants R46
  compares with or bounds its reads by: kind "value"), DBF_FN_* defines (the game functions the port calls: the bound
  functions given a "define", each with the witnesses that guard it), and the witness table (DbfWitness) and the
  mission blacklist table (DbfBlacklistKind), defined in the one translation unit that defines DBF_ADDRESSES_DEFINE;
- the kind-name header: the name of each vanilla stratagem type, from HellForge's hellforge_content.h;
- the receipt: SHA-256 of game.dll and of every input, and for every address and witness its value, source and
  check result. It records inputs by file name only.

Checks, all of which must pass before anything is written:
- game.dll is build 25480438 (PE TimeDateStamp 0x6AB3B43F);
- every address, value and bound function's cited R46 line holds it (or its expression, for a computed offset): an RVA
  as a hex literal, an offset or a value as a hex or a decimal literal (R46 writes small offsets and counts in decimal).
  An expression is integer literals joined by + and * with parentheses (eval_expr); it must equal the value and stand
  on the line as written;
- every function define is guarded by at least one emitted witness, every witness it names exists, and each emitted
  one carries the function's features (so refusing any of them refuses every feature that calls the function);
- every blacklist kind's cited mission_blacklist.lua line names that kind with that name;
- every guards.lua witness has exactly one assignment, and a witness lying within 0x4000 above a bound function the
  port uses carries that function's features (R46's deferred-witness rule: it belongs to that function's body);
- every emitted witness's bytes match game.dll ("file"), or lie where the file has no raw data ("unreadable"), or are
  marked "expect_differs" and lie in a section whose raw data is packed on disk (entropy near 8 bits per byte and no
  x64 prologues). Any other difference fails the run, naming every such witness.
"""
