#!/usr/bin/env python3
"""Generates Diver's Best Friend's address table for game build 25480438.

Usage (from hellforge/):
    python3 -I tools/map_addresses.py <R46 native-selection-poc> <game.dll> \\
        divers-best-friend/src/addresses_25480438.h receipts/addresses-25480438.json \\
        [--table tools/addresses_25480438.json] [--content-header hellforge_content.h] \\
        [--kind-names divers-best-friend/src/kind_names_25480438.h]
The defaults: the table beside this script, $HF_SDK (or $HF_INSTALL/app/sdk, ~/Applications/HellForge by default)
for hellforge_content.h, and kind_names_25480438.h beside the address header.

R46 (the last Lua DBF built for 25480438, its HellForge native-selection-poc folder) holds the build's addresses inline
in its Lua. tools/addresses_25480438.json names the ones the C port uses, each with the R46 line it comes from, and
assigns every R46 witness (guards.lua) the features it gates, or drops it. This script checks all of that and writes:

- the address header: DBF_FEATURE_*, DBF_RVA_* and DBF_OFF_* defines, and the witness table (DbfWitness), defined in
  the one translation unit that defines DBF_ADDRESSES_DEFINE;
- the kind-name header: the name of each vanilla stratagem type, from HellForge's hellforge_content.h;
- the receipt: SHA-256 of game.dll and of every input, and for every address and witness its value, source and
  check result. It records inputs by file name only.

Checks, all of which must pass before anything is written:
- game.dll is build 25480438 (PE TimeDateStamp 0x6AB3B43F);
- every address and bound function's cited R46 line holds its value (or its expression, for a computed offset);
- every guards.lua witness has exactly one assignment, and a witness lying within 0x4000 above a bound function the
  port uses carries that function's features (R46's deferred-witness rule: it belongs to that function's body);
- every emitted witness's bytes match game.dll ("file"), or lie where the file has no raw data ("unreadable"), or are
  marked "expect_differs" and lie in a section whose raw data is packed on disk (entropy near 8 bits per byte and no
  x64 prologues). Any other difference fails the run, naming every such witness.
"""
import argparse
import collections
import hashlib
import json
import math
import os
import re
import struct
import sys
import textwrap
from dataclasses import dataclass

BUILD = "25480438"
GAME_DLL_STAMP = 0x6AB3B43F
# Admission's Feature order (Task 6). A witness's features are a mask of 1u << index.
FEATURES = ("STATE", "STRATAGEMS", "HUD_READ", "LIST_OPACITY", "ENTRY", "SCRAMBLE", "POINTING", "CAMERA", "LATCH",
            "SOUND", "DOCK", "WEAPON", "TERMINAL")
REACH = 0x4000              # a code witness belongs to the nearest bound function at or below it, within this
KIND_SLOTS = 150            # dbf_kind_names[150], indexed by stratagem type
PACKED_ENTROPY = 7.99       # bits per byte over a section's raw data: encrypted, not code
PROLOGUES = (b"\x48\x89\x5c\x24\x08", b"\x48\x89\x5c\x24\x10", b"\x48\x83\xec\x28", b"\x40\x53\x48\x83\xec\x20")
GENERATED = "Generated by tools/map_addresses.py"


class GeneratorError(Exception):
    pass


# --- R46 guards.lua -------------------------------------------------------------------------------------------

@dataclass(frozen=True)
class Guard:
    name: str
    rva: int
    data: bytes
    line: int


_GUARD = re.compile(r"\{\s*name\s*=\s*(?P<q1>['\"])(?P<name>[A-Za-z0-9_]+)(?P=q1)\s*,"
                    r"\s*rva\s*=\s*0x(?P<rva>[0-9A-Fa-f]+)\s*,"
                    r"\s*bytes\s*=\s*(?P<q2>['\"])(?P<bytes>[^'\"\n]*)(?P=q2)\s*\}")
_GUARD_START = re.compile(r"\{\s*name\s*=")
_HEX_ESCAPES = re.compile(r"(?:\\x[0-9A-Fa-f]{2})*")


def parse_guards(text):
    """Every {name='…',rva=0x…,bytes='\\x..'} entry of R46's guards.lua, in file order, with its line number."""
    guards, seen, problems = [], set(), []
    matched = set()
    for m in _GUARD.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        matched.add(m.start())
        raw = m.group("bytes")
        if not _HEX_ESCAPES.fullmatch(raw):
            problems.append("guards.lua:%d: %s: bytes may only hold \\xHH escapes" % (line, m.group("name")))
            continue
        name = m.group("name")
        if name in seen:
            problems.append("guards.lua:%d: witness %s appears twice" % (line, name))
            continue
        seen.add(name)
        data = bytes(int(raw[i + 2:i + 4], 16) for i in range(0, len(raw), 4))
        guards.append(Guard(name, int(m.group("rva"), 16), data, line))
    for m in _GUARD_START.finditer(text):
        if m.start() not in matched:
            problems.append("guards.lua:%d: an entry this script cannot read" % (text.count("\n", 0, m.start()) + 1))
    if problems:
        raise GeneratorError("\n".join(problems))
    return guards


# --- game.dll ---------------------------------------------------------------------------------------------------

@dataclass(frozen=True)
class Section:
    index: int          # 1-based, as the section table lists them (the packed sections have no names)
    name: str
    va: int
    vsize: int
    raw_ptr: int
    raw_size: int

    @property
    def label(self):
        return "#%d%s" % (self.index, " " + self.name if self.name else "")


class PeImage:
    """The parts of a PE32+ file this script needs: the stamp, the image size and the section table."""

    def __init__(self, data):
        self.data = data
        try:
            if data[:2] != b"MZ":
                raise GeneratorError("game.dll is not a PE file (no MZ header)")
            pe = struct.unpack_from("<I", data, 0x3C)[0]
            if data[pe:pe + 4] != b"PE\0\0":
                raise GeneratorError("game.dll is not a PE file (no PE signature)")
            count, self.stamp = struct.unpack_from("<HI", data, pe + 6)
            optional_size = struct.unpack_from("<H", data, pe + 20)[0]
            optional = pe + 24
            if struct.unpack_from("<H", data, optional)[0] != 0x20B:
                raise GeneratorError("game.dll is not a PE32+ image")
            self.image_size = struct.unpack_from("<I", data, optional + 56)[0]
            self.sections = []
            for i in range(count):
                at = optional + optional_size + 40 * i
                name = data[at:at + 8].rstrip(b"\0").decode("ascii", "replace").strip()
                vsize, va, raw_size, raw_ptr = struct.unpack_from("<IIII", data, at + 8)
                self.sections.append(Section(i + 1, name, va, vsize, raw_ptr, raw_size))
        except struct.error as e:
            raise GeneratorError("game.dll is truncated: %s" % e) from None
        self._packed = {}

    def section_of(self, rva):
        for s in self.sections:
            if s.va <= rva < s.va + max(s.vsize, s.raw_size):
                return s
        return None

    def file_offset(self, rva, size):
        """The file offset of [rva, rva + size), or None when the file has no raw data for all of it."""
        s = self.section_of(rva)
        if s is None:
            raise GeneratorError("RVA 0x%x is in no section of game.dll" % rva)
        covered = min(s.raw_size, s.vsize) if s.vsize else s.raw_size
        if s.raw_size == 0 or rva - s.va + size > covered or s.raw_ptr + covered > len(self.data):
            return None
        return s.raw_ptr + (rva - s.va)

    def check(self, rva, expected):
        offset = self.file_offset(rva, len(expected))
        if offset is None:
            return "unreadable", None
        return ("file" if self.data[offset:offset + len(expected)] == expected else "differs"), offset

    def packed(self, section):
        """Whether a section's raw data is encrypted on disk: (packed, entropy in bits per byte, prologue count)."""
        if section.index not in self._packed:
            raw = self.data[section.raw_ptr:section.raw_ptr + section.raw_size]
            entropy = 0.0
            if raw:
                for n in collections.Counter(raw).values():
                    entropy -= n / len(raw) * math.log2(n / len(raw))
            prologues = sum(raw.count(p) for p in PROLOGUES)
            self._packed[section.index] = (bool(raw) and entropy >= PACKED_ENTROPY and prologues == 0,
                                           round(entropy, 5), prologues)
        return self._packed[section.index]


# --- hellforge_content.h ----------------------------------------------------------------------------------------

_KIND = re.compile(r"^#define HF_STRATAGEM_[A-Z0-9_]+\s+(\d+)u\s+/\*\s*(.*?)\s*\*/\s*$")


def parse_kind_names(text):
    """{type: name} from the SDK's `#define HF_STRATAGEM_<X> <type>u /* <name> - … */` lines."""
    names, problems = {}, []
    for number, line in enumerate(text.splitlines(), 1):
        m = _KIND.match(line)
        if not m:
            if line.startswith("#define HF_STRATAGEM_"):
                problems.append("hellforge_content.h:%d: a stratagem line this script cannot read" % number)
            continue
        kind, name = int(m.group(1)), m.group(2).split(" - ", 1)[0].strip()
        if not 0 < kind < KIND_SLOTS:
            problems.append("hellforge_content.h:%d: type %d does not fit dbf_kind_names[%d]" % (number, kind,
                                                                                               KIND_SLOTS))
        elif kind in names:
            problems.append("hellforge_content.h:%d: type %d is named twice" % (number, kind))
        elif not name:
            problems.append("hellforge_content.h:%d: type %d has no name" % (number, kind))
        else:
            names[kind] = name
    if not names and not problems:
        problems.append("hellforge_content.h names no stratagem types")
    if problems:
        raise GeneratorError("\n".join(problems))
    return names


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '\\"':
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def c_comment(text):
    return text.replace("*/", "* /")


# --- the address table ------------------------------------------------------------------------------------------

_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
_HEX = re.compile(r"^0x[0-9a-f]+$")
_SOURCE_PART = re.compile(r"^([A-Za-z0-9_]+\.lua):(\d+)$")


def _hex(value):
    return "0x%x" % value


def _parse_hex(text, where, problems):
    if not isinstance(text, str) or not _HEX.match(text):
        problems.append("%s: value %r is not a lower-case 0x… hex string" % (where, text))
        return None
    return int(text, 16)


class R46Files:
    """R46's Lua files, read once each, by name."""

    def __init__(self, folder):
        self.folder = folder
        self.lines = {}
        self.hashes = {}

    def line(self, name, number):
        if name not in self.lines:
            path = os.path.join(self.folder, name)
            if not os.path.isfile(path):
                raise GeneratorError("R46 has no %s" % name)
            with open(path, "rb") as f:
                data = f.read()
            self.hashes[name] = hashlib.sha256(data).hexdigest()
            self.lines[name] = [line.rstrip("\r") for line in data.decode("latin-1").split("\n")]
        lines = self.lines[name]
        return lines[number - 1] if 0 < number <= len(lines) else None


def _check_source(what, entry, value, r46, problems):
    """The source names R46 lines; each must hold the value as a hex literal, or the entry's expression."""
    source = entry.get("source")
    if not isinstance(source, str) or not source.startswith("R46 "):
        problems.append("%s: source %r does not start with 'R46 '" % (what, source))
        return
    expr = entry.get("expr")
    if expr is not None:
        terms = expr.split("+") if isinstance(expr, str) else []
        if not terms or not all(_HEX.match(t) for t in terms):
            problems.append("%s: expr %r is not a sum of 0x… terms" % (what, expr))
            return
        if sum(int(t, 16) for t in terms) != value:
            problems.append("%s: expr %s is 0x%x, not %s" % (what, expr, sum(int(t, 16) for t in terms),
                                                              _hex(value)))
            return
    literal = re.compile(r"(?<![0-9A-Za-z_])0x0*%x(?![0-9A-Fa-f])" % value, re.I)
    for part in source[4:].split(", "):
        m = _SOURCE_PART.match(part)
        if not m:
            problems.append("%s: cannot read source %r (expected file.lua:line)" % (what, part))
            continue
        try:
            text = r46.line(m.group(1), int(m.group(2)))
        except GeneratorError as e:
            problems.append("%s: %s" % (what, e))
            continue
        if text is None:
            problems.append("%s: R46 %s has no line %s" % (what, m.group(1), m.group(2)))
        elif not literal.search(text) and not (expr and expr in re.sub(r"\s+", "", text)):
            problems.append("%s: R46 %s does not hold %s%s" % (what, part, _hex(value),
                                                                 " or " + expr if expr else ""))


def _features(what, entry, problems):
    """(features list in Feature order, dropped) from an entry's "features" or "dropped"."""
    has_features, dropped = "features" in entry, entry.get("dropped") is True
    if has_features == dropped or ("dropped" in entry and not dropped):
        problems.append("%s: give either \"features\" or \"dropped\": true" % what)
        return [], False
    if dropped:
        return [], True
    names = entry["features"]
    if not isinstance(names, list) or not names or len(set(names)) != len(names) \
            or not all(n in FEATURES for n in names):
        problems.append("%s: features %r must be distinct names from %s" % (what, names, ", ".join(FEATURES)))
        return [], False
    return [f for f in FEATURES if f in names], False


def _mask(features):
    return " | ".join("(1u << DBF_FEATURE_%s)" % f for f in features)


def _sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    temporary = path + ".tmp"
    with open(temporary, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(temporary, path)


def generate(r46_dir, dll_path, out_h, receipt_path, table_path, content_header, kind_names_out):
    """Checks everything, then writes the two headers and the receipt; returns the receipt. Raises GeneratorError
    listing every problem, and writes nothing, when a check fails."""
    with open(dll_path, "rb") as f:
        dll = f.read()
    pe = PeImage(dll)
    if pe.stamp != GAME_DLL_STAMP:
        raise GeneratorError("game.dll stamp 0x%08x is not build %s (0x%08x)" % (pe.stamp, BUILD, GAME_DLL_STAMP))
    guards_path = os.path.join(r46_dir, "guards.lua")
    if not os.path.isfile(guards_path):
        raise GeneratorError("%s has no guards.lua (expected R46's native-selection-poc folder)" % r46_dir)
    with open(guards_path, "rb") as f:
        guards_data = f.read()
    guards = parse_guards(guards_data.decode("latin-1"))
    with open(table_path, encoding="utf-8") as f:
        table = json.load(f)
    if table.get("build") != BUILD:
        raise GeneratorError("%s is for build %r, not %s" % (os.path.basename(table_path), table.get("build"), BUILD))
    with open(content_header, encoding="utf-8") as f:
        kind_names = parse_kind_names(f.read())
    r46 = R46Files(r46_dir)
    problems = []

    # Addresses.
    addresses, names = [], set()
    for i, entry in enumerate(table.get("addresses", [])):
        name = entry.get("name")
        what = "address %s" % (name or "#%d" % (i + 1))
        if not isinstance(name, str) or not _NAME.match(name) or name in names:
            problems.append("%s: name must be unique and UPPER_CASE" % what)
            continue
        names.add(name)
        kind = entry.get("kind")
        if kind not in ("rva", "offset"):
            problems.append("%s: kind %r is neither \"rva\" nor \"offset\"" % (what, kind))
            continue
        value = _parse_hex(entry.get("value"), what, problems)
        if value is None:
            continue
        if value >= 1 << 32:
            problems.append("%s: %s does not fit 32 bits" % (what, _hex(value)))
        if kind == "rva" and (value >= pe.image_size or pe.section_of(value) is None):
            problems.append("%s: RVA %s is outside game.dll's sections" % (what, _hex(value)))
        _check_source(what, entry, value, r46, problems)
        row = {"name": name, "kind": kind, "value": _hex(value),
               "define": ("DBF_RVA_" if kind == "rva" else "DBF_OFF_") + name, "source": entry.get("source")}
        if "expr" in entry:
            row["expr"] = entry["expr"]
        addresses.append(row)
    if not addresses:
        problems.append("the table has no addresses")

    # Bound functions: the game functions R46 calls (base+0x… cast to a function), and whether the port calls them.
    functions = []
    for name, entry in sorted(table.get("bound_functions", {}).items()):
        what = "bound function %s" % name
        rva = _parse_hex(entry.get("rva"), what, problems)
        features, dropped = _features(what, entry, problems)
        if rva is None:
            continue
        _check_source(what, entry, rva, r46, problems)
        if dropped and not entry.get("reason"):
            problems.append("%s: a dropped function needs a reason" % what)
        functions.append({"name": name, "rva": rva, "features": features, "dropped": dropped,
                          "reason": entry.get("reason"), "source": entry.get("source")})
    functions.sort(key=lambda f: f["rva"])

    # Witnesses.
    assignments = table.get("witnesses", {})
    guard_names = {g.name for g in guards}
    for name in sorted(guard_names - set(assignments)):
        problems.append("witness %s (guards.lua) has no assignment in the table" % name)
    for name in sorted(set(assignments) - guard_names):
        problems.append("witness %s is assigned in the table but is not in guards.lua" % name)
    witnesses, differs = [], []
    for g in guards:
        entry = assignments.get(g.name)
        if entry is None:
            continue
        what = "witness %s" % g.name
        features, dropped = _features(what, entry, problems)
        reason = entry.get("reason")
        if not isinstance(reason, str) or not reason.strip():
            problems.append("%s: needs a one-line reason" % what)
        expect = entry.get("file_check")
        if expect not in (None, "expect_differs"):
            problems.append("%s: file_check %r is not \"expect_differs\"" % (what, expect))
        if expect and not (isinstance(entry.get("file_check_reason"), str) and entry["file_check_reason"].strip()):
            problems.append("%s: expect_differs needs a file_check_reason" % what)
        if len(g.data) > 0xFFFF:
            problems.append("%s: %d bytes do not fit DbfWitness.size" % (what, len(g.data)))
        if not dropped and not g.data:
            problems.append("%s: has no bytes in guards.lua and cannot be emitted" % what)

        # R46's deferred-witness rule.
        owner = None
        for f in functions:
            if 0 <= g.rva - f["rva"] < REACH and (owner is None or f["rva"] > owner["rva"]):
                owner = f
        if owner and not owner["dropped"] and (dropped or not set(owner["features"]) <= set(features)):
            problems.append("%s lies +0x%x above bound function %s (0x%x; %s) but is assigned %s: it belongs to "
                            "that function and needs its features" % (
                                what, g.rva - owner["rva"], owner["name"], owner["rva"],
                                ", ".join(owner["features"]), "dropped" if dropped else ", ".join(features)))

        # The file check.
        section = pe.section_of(g.rva)
        if section is None:
            problems.append("%s: RVA 0x%x is in no section of game.dll" % (what, g.rva))
            continue
        if g.data:
            check, offset = pe.check(g.rva, g.data)
        else:
            check, offset = "empty", None
        if expect == "expect_differs":
            if check == "differs":
                packed, entropy, prologues = pe.packed(section)
                if packed:
                    check = "expect_differs"
                else:
                    problems.append("%s is marked expect_differs but section %s is not packed on disk (raw entropy "
                                    "%.5f bits per byte, %d x64 prologues): the difference is real" % (
                                        what, section.label, entropy, prologues))
            else:
                problems.append("%s is marked expect_differs but the file check says %s: remove the mark" % (
                    what, check))
        if check == "differs" and not dropped:
            differs.append("witness %s (0x%x, %d bytes, guards.lua:%d) differs from game.dll at file offset 0x%x: "
                           "expected %s, the file has %s" % (g.name, g.rva, len(g.data), g.line, offset,
                                                              g.data.hex(), dll[offset:offset + len(g.data)].hex()))
        row = {"name": g.name, "rva": _hex(g.rva), "size": len(g.data), "guards_line": g.line}
        if dropped:
            row["dropped"] = True
        else:
            row["features"] = features
        row["reason"] = reason
        row["nearest_bound_function"] = None if owner is None else {
            "name": owner["name"], "rva": _hex(owner["rva"]), "distance": _hex(g.rva - owner["rva"])}
        row["section"] = section.label
        row["file_offset"] = None if offset is None else _hex(offset)
        row["check"] = check
        if expect:
            row["file_check_reason"] = entry.get("file_check_reason")
        witnesses.append((g, row))
    problems.extend(differs)
    if problems:
        raise GeneratorError("\n".join(problems))

    # Outputs.
    receipt_name = os.path.basename(receipt_path)
    dll_sha = hashlib.sha256(dll).hexdigest()
    emitted = [(g, row) for g, row in witnesses if not row.get("dropped")]
    header = [
        "/* %s. Do not edit by hand: change tools/addresses_25480438.json and run it again." % GENERATED,
        "   Inputs: that table, R46's guards.lua and the game.dll of build %s, SHA-256" % BUILD,
        "   %s." % dll_sha,
        "   The receipt, %s, says where every value came from and how each witness was checked." % receipt_name,
        "   Define DBF_ADDRESSES_DEFINE in exactly one translation unit (admission.c) before including this header. */",
        "#ifndef DBF_ADDRESSES_25480438_H",
        "#define DBF_ADDRESSES_25480438_H",
        "",
        "#include <stdint.h>",
        "",
        "/* Features in admission's order. DbfWitness.features is a mask of (1u << DBF_FEATURE_*). */",
    ]
    header += ["#define DBF_FEATURE_%s %d" % (f, i) for i, f in enumerate(FEATURES)]
    header += ["#define DBF_FEATURE_COUNT %d" % len(FEATURES), "",
               "/* Globals (RVAs in game.dll) and offsets, from R46. */"]
    for a in addresses:
        note = ("%s; " % a["expr"] if "expr" in a else "") + a["source"]
        header.append("#define %s %su /* %s */" % (a["define"], a["value"], c_comment(note)))
    header += [
        "",
        "typedef struct {",
        "    const char* name;",
        "    uint32_t rva;",
        "    uint16_t size;",
        "    uint32_t features;",
        "    const uint8_t* bytes;",
        "} DbfWitness;",
        "",
        "extern const DbfWitness dbf_witnesses[];",
        "extern const int dbf_witness_count;",
        "",
        "#ifdef DBF_ADDRESSES_DEFINE",
    ]
    for g, row in emitted:
        comment = "/* %s: guards.lua:%d, %s; %s */" % (g.name, g.line, row["check"], c_comment(row["reason"]))
        header += textwrap.wrap(comment, 120, subsequent_indent="   ", break_long_words=False, break_on_hyphens=False)
        header.append("static const uint8_t dbf_w_%s[%d] = {" % (g.name, len(g.data)))
        for i in range(0, len(g.data), 16):
            header.append("    " + ", ".join("0x%02x" % b for b in g.data[i:i + 16]) + ",")
        header.append("};")
    header.append("")
    header.append("const DbfWitness dbf_witnesses[] = {")
    for g, row in emitted:
        header.append('    { "%s", 0x%xu, %d, %s, dbf_w_%s },' % (g.name, g.rva, len(g.data), _mask(row["features"]),
                                                                 g.name))
    header += [
        "};",
        "const int dbf_witness_count = (int)(sizeof dbf_witnesses / sizeof dbf_witnesses[0]);",
        "#endif",
        "",
        "#endif",
        "",
    ]
    header_text = "\n".join(header)

    content_sha = _sha256(content_header)
    kinds = [
        "/* %s. Do not edit by hand: run it again when the SDK changes." % GENERATED,
        "   The name of every vanilla stratagem type of build %s, indexed by type (unnamed types are NULL)," % BUILD,
        "   from HellForge's hellforge_content.h, SHA-256 %s. */" % content_sha,
        "#ifndef DBF_KIND_NAMES_25480438_H",
        "#define DBF_KIND_NAMES_25480438_H",
        "",
        "static const char* const dbf_kind_names[%d] = {" % KIND_SLOTS,
    ]
    kinds += ["    [%d] = %s," % (k, c_string(kind_names[k])) for k in sorted(kind_names)]
    kinds += ["};", "", "#endif", ""]
    kinds_text = "\n".join(kinds)

    checks = collections.Counter(row["check"] for _, row in emitted)
    dropped_checks = collections.Counter(row["check"] for _, row in witnesses if row.get("dropped"))
    per_feature = {f: sum(1 for _, row in emitted if f in row["features"]) for f in FEATURES}
    compared = sorted({pe.section_of(g.rva).index for g, row in witnesses if row["file_offset"] is not None})
    sections = []
    for s in pe.sections:
        info = {"section": s.label, "va": _hex(s.va), "virtual_size": _hex(s.vsize), "raw_size": _hex(s.raw_size)}
        if s.index in compared:
            packed, entropy, prologues = pe.packed(s)
            info.update({"raw_entropy": entropy, "x64_prologues": prologues, "packed_on_disk": packed})
        sections.append(info)
    inputs = {os.path.basename(table_path): _sha256(table_path),
              "guards.lua": hashlib.sha256(guards_data).hexdigest(),
              os.path.basename(content_header): content_sha}
    inputs.update(r46.hashes)
    receipt = {
        "generator": "tools/map_addresses.py",
        "game_build": BUILD,
        "game_dll": {"file": os.path.basename(dll_path), "sha256": dll_sha, "bytes": len(dll),
                     "time_date_stamp": "0x%08x" % pe.stamp, "image_size": _hex(pe.image_size)},
        "inputs": dict(sorted(inputs.items())),
        "outputs": {os.path.basename(out_h): hashlib.sha256(header_text.encode()).hexdigest(),
                    os.path.basename(kind_names_out): hashlib.sha256(kinds_text.encode()).hexdigest()},
        "tally": {
            "witnesses": len(witnesses),
            "emitted": len(emitted),
            "dropped": len(witnesses) - len(emitted),
            "emitted_checks": dict(sorted(checks.items())),
            "dropped_checks": dict(sorted(dropped_checks.items())),
            "emitted_per_feature": per_feature,
            "addresses": len(addresses),
            "kind_names": len(kind_names),
        },
        "sections": sections,
        "addresses": addresses,
        "bound_functions": [{"name": f["name"], "rva": _hex(f["rva"]),
                             **({"dropped": True, "reason": f["reason"]} if f["dropped"]
                                else {"features": f["features"]}),
                             "source": f["source"]} for f in functions],
        "witnesses": [row for _, row in witnesses],
    }
    _write(out_h, header_text)
    _write(kind_names_out, kinds_text)
    _write(receipt_path, json.dumps(receipt, indent=2, ensure_ascii=False) + "\n")
    return receipt


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    install = os.environ.get("HF_INSTALL", os.path.expanduser("~/Applications/HellForge"))
    sdk = os.environ.get("HF_SDK", os.path.join(install, "app", "sdk"))
    parser = argparse.ArgumentParser(description="Generate DBF's address table for game build %s." % BUILD)
    parser.add_argument("r46", help="R46's native-selection-poc folder (holds guards.lua)")
    parser.add_argument("game_dll", help="game.dll of build %s" % BUILD)
    parser.add_argument("out_h", help="the address header to write (src/addresses_25480438.h)")
    parser.add_argument("receipt", help="the receipt to write (receipts/addresses-25480438.json)")
    parser.add_argument("--table", default=os.path.join(here, "addresses_25480438.json"))
    parser.add_argument("--content-header", default=os.path.join(sdk, "hellforge_content.h"))
    parser.add_argument("--kind-names", help="the kind-name header to write (default: kind_names_25480438.h beside "
                                             "the address header)")
    args = parser.parse_args(argv)
    kind_names = args.kind_names or os.path.join(os.path.dirname(os.path.abspath(args.out_h)),
                                                 "kind_names_25480438.h")
    try:
        receipt = generate(args.r46, args.game_dll, args.out_h, args.receipt, args.table, args.content_header,
                           kind_names)
    except (GeneratorError, OSError, ValueError) as e:
        print("map_addresses: %s" % e, file=sys.stderr)
        return 1
    tally = receipt["tally"]
    print("Wrote %s, %s and %s: %d addresses, %d witnesses emitted (%s), %d dropped, %d kind names." % (
        args.out_h, kind_names, args.receipt, tally["addresses"], tally["emitted"],
        ", ".join("%d %s" % (n, c) for c, n in tally["emitted_checks"].items()), tally["dropped"],
        tally["kind_names"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
